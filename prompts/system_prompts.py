"""Bina 的人设、状态和互动提示词。"""

MOOD_CONTEXT_BLOCK_TEMPLATE = """【当前状态感知】（系统实时状态引擎，非用户输入）：
{mood_context}
{style_guidance}
"""


def with_mood_context(system_prompt: str, mood_context: str, style_guidance: str) -> str:
    """把 mood_engine 的状态描述拼进任意人格的 system prompt 末尾，供所有节点共用。"""
    block = MOOD_CONTEXT_BLOCK_TEMPLATE.format(
        mood_context=mood_context, style_guidance=style_guidance
    )
    return f"{system_prompt}\n\n{block}"


